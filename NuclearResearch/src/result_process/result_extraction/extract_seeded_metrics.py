#!/usr/bin/env python3
"""
Extract and Aggregate Metrics from Seeded Rerun Visualization Summaries

Reads metrics_summary.txt files generated by visualize_seeded_rerun.py
and produces:
  1. Per-seed CSV: individual MAE/RMSE for each (experiment, model, horizon, seed)
  2. Aggregated CSV: mean +/- std of MAE/RMSE across seeds

Uses the same regex extraction as extract_metrics.py to ensure consistency
with the rolling-window MAE/RMSE methodology.

Usage:
    python extract_seeded_metrics.py
    python extract_seeded_metrics.py --quiet
"""

import argparse
import re
import csv
from pathlib import Path
from typing import Optional, Tuple, List, Dict

import numpy as np

# Derive project root from script location
# Script is at: <PROJECT_ROOT>/NuclearResearch/src/result_process/result_extraction/
PROJECT_ROOT = Path(__file__).resolve().parents[4]

# ============================================================================
# CONFIGURATION
# ============================================================================

VISUALIZATION_ROOT = PROJECT_ROOT / 'NuclearResearch' / 'results' / 'Visualization_seeded'
OUTPUT_DIR = PROJECT_ROOT / 'NuclearResearch' / 'results_summary'

EXPERIMENTS = ['exp0', 'exp4']
HORIZONS = ['30s', '300s', '600s']
MODELS = ['SCINet', 'Crossformer', 'Pyraformer', 'LSTM', 'GRU', 'SegRNN']
SEEDS = [42, 123, 456, 789, 1024]


# ============================================================================
# EXTRACTION FUNCTIONS
# ============================================================================

def extract_average_metrics(summary_file: Path) -> Optional[Tuple[float, float]]:
    """
    Extract Average MAE and RMSE from metrics summary file.

    Uses the same regex as extract_metrics.py for consistency.

    Args:
        summary_file: Path to *_ahead_metrics_summary.txt

    Returns:
        (mae, rmse) tuple, or None if file not found or parse error
    """
    if not summary_file.exists():
        return None

    try:
        with open(summary_file, 'r') as f:
            content = f.read()

        mae_match = re.search(r'Average MAE:\s+([\d.]+)', content)
        rmse_match = re.search(r'Average RMSE:\s+([\d.]+)', content)

        if mae_match and rmse_match:
            mae = float(mae_match.group(1))
            rmse = float(rmse_match.group(1))
            return (mae, rmse)

        return None

    except Exception as e:
        print('ERROR parsing {}: {}'.format(summary_file, e))
        return None


def get_seeded_metrics_file_path(exp: str, model: str, horizon: str, seed: int) -> Path:
    """
    Get path to metrics summary file for a seeded run.

    Structure: {VISUALIZATION_ROOT}/{exp}/{horizon}_ahead/seed{seed}/{model}_{horizon}_ahead_metrics_summary.txt

    Args:
        exp: Experiment ID (exp0 or exp4)
        model: Model name
        horizon: Horizon name (30s, 300s, 600s)
        seed: Random seed value

    Returns:
        Path to metrics summary file
    """
    horizon_folder = '{}_ahead'.format(horizon)
    seed_folder = 'seed{}'.format(seed)
    filename = '{}_{}_ahead_metrics_summary.txt'.format(model, horizon)
    return VISUALIZATION_ROOT / exp / horizon_folder / seed_folder / filename


# ============================================================================
# MAIN EXTRACTION LOGIC
# ============================================================================

def extract_all_seeded_metrics(verbose: bool = True) -> List[Dict]:
    """
    Extract metrics from all seeded rerun results.

    Returns:
        List of dictionaries with keys: experiment, model, horizon, seed, mae, rmse
    """
    all_metrics = []

    for exp in EXPERIMENTS:
        if verbose:
            print('\nProcessing {}...'.format(exp.upper()))

        exp_found = 0

        for model in MODELS:
            for horizon in HORIZONS:
                for seed in SEEDS:
                    summary_file = get_seeded_metrics_file_path(exp, model, horizon, seed)
                    metrics = extract_average_metrics(summary_file)

                    if metrics is None:
                        if verbose:
                            print('  SKIP: {:15s} {:5s} seed={} - No metrics file'.format(
                                model, horizon, seed))
                        continue

                    mae, rmse = metrics

                    all_metrics.append({
                        'experiment': exp,
                        'model': model,
                        'horizon': horizon,
                        'seed': seed,
                        'mae': mae,
                        'rmse': rmse
                    })

                    exp_found += 1

                    if verbose:
                        print('  OK:   {:15s} {:5s} seed={} - MAE={:.2f}, RMSE={:.2f}'.format(
                            model, horizon, seed, mae, rmse))

        if verbose:
            print('  Total: {} metrics found for {}'.format(exp_found, exp))

    return all_metrics


def aggregate_metrics(all_metrics: List[Dict]) -> List[Dict]:
    """
    Compute mean and std of MAE/RMSE across seeds for each (experiment, model, horizon).

    Args:
        all_metrics: Per-seed metrics list

    Returns:
        List of aggregated dictionaries
    """
    agg_rows = []

    for exp in EXPERIMENTS:
        for model in MODELS:
            for horizon in HORIZONS:
                seed_data = [
                    r for r in all_metrics
                    if r['experiment'] == exp
                    and r['model'] == model
                    and r['horizon'] == horizon
                ]

                if not seed_data:
                    continue

                maes = [r['mae'] for r in seed_data]
                rmses = [r['rmse'] for r in seed_data]

                agg_rows.append({
                    'experiment': exp,
                    'model': model,
                    'horizon': horizon,
                    'n_seeds': len(seed_data),
                    'mae_mean': float(np.mean(maes)),
                    'mae_std': float(np.std(maes)),
                    'rmse_mean': float(np.mean(rmses)),
                    'rmse_std': float(np.std(rmses)),
                })

    return agg_rows


def save_per_seed_csv(metrics: List[Dict], output_file: Path):
    """Save per-seed metrics to CSV."""
    output_file.parent.mkdir(parents=True, exist_ok=True)

    with open(output_file, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=[
            'experiment', 'model', 'horizon', 'seed', 'mae', 'rmse'
        ])
        writer.writeheader()
        writer.writerows(metrics)

    print('Saved {} per-seed metrics to: {}'.format(len(metrics), output_file))


def save_aggregated_csv(agg_metrics: List[Dict], output_file: Path):
    """Save aggregated (mean +/- std) metrics to CSV."""
    output_file.parent.mkdir(parents=True, exist_ok=True)

    with open(output_file, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=[
            'experiment', 'model', 'horizon', 'n_seeds',
            'mae_mean', 'mae_std', 'rmse_mean', 'rmse_std'
        ])
        writer.writeheader()
        writer.writerows(agg_metrics)

    print('Saved {} aggregated metrics to: {}'.format(len(agg_metrics), output_file))


# ============================================================================
# MAIN
# ============================================================================

def main():
    parser = argparse.ArgumentParser(
        description='Extract and aggregate metrics from seeded rerun visualizations'
    )

    parser.add_argument(
        '--quiet',
        action='store_true',
        help='Minimal output'
    )

    args = parser.parse_args()
    verbose = not args.quiet

    print('=' * 80)
    print('EXTRACTING SEEDED RERUN METRICS')
    print('=' * 80)
    print('Source: {}'.format(VISUALIZATION_ROOT))
    print('Experiments: {}'.format(', '.join(EXPERIMENTS)))
    print('Models: {}'.format(', '.join(MODELS)))
    print('Seeds: {}'.format(SEEDS))
    print()

    # Extract per-seed metrics
    all_metrics = extract_all_seeded_metrics(verbose=verbose)

    if not all_metrics:
        print('\nNo metrics found. Ensure visualize_seeded_rerun.py has been run first.')
        return

    # Save per-seed CSV
    per_seed_file = OUTPUT_DIR / 'seeded_rerun_per_seed_metrics.csv'
    save_per_seed_csv(all_metrics, per_seed_file)

    # Compute and save aggregated CSV
    agg_metrics = aggregate_metrics(all_metrics)
    agg_file = OUTPUT_DIR / 'seeded_rerun_aggregated_metrics.csv'
    save_aggregated_csv(agg_metrics, agg_file)

    # Summary
    print()
    print('=' * 80)
    print('SUMMARY')
    print('=' * 80)
    print('  Per-seed metrics: {} entries'.format(len(all_metrics)))
    print('  Aggregated groups: {} (experiment x model x horizon)'.format(len(agg_metrics)))
    print()
    print('Output files:')
    print('  Per-seed:    {}'.format(per_seed_file))
    print('  Aggregated:  {}'.format(agg_file))
    print()

    # Print aggregated table
    if agg_metrics:
        print('{:<8s} {:15s} {:6s} {:>3s}  {:>10s}  {:>10s}'.format(
            'Exp', 'Model', 'Horiz', 'N', 'MAE (mean+/-std)', 'RMSE (mean+/-std)'))
        print('-' * 70)
        for row in agg_metrics:
            print('{:<8s} {:15s} {:6s} {:3d}  {:7.2f}+/-{:<5.2f}  {:7.2f}+/-{:<5.2f}'.format(
                row['experiment'], row['model'], row['horizon'],
                row['n_seeds'],
                row['mae_mean'], row['mae_std'],
                row['rmse_mean'], row['rmse_std']))

    print('=' * 80)


if __name__ == '__main__':
    main()

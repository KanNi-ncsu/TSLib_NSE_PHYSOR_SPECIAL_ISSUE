#!/usr/bin/env python3
"""
Extract Metrics from Visualization Summary Files

Reads all *_ahead_metrics_summary.txt files generated by visualization scripts
and extracts Average MAE and RMSE values for comprehensive analysis.

Output: CSV file with all metrics across experiments, models, and horizons

Usage:
    python extract_metrics.py
    python extract_metrics.py --output custom_output.csv
"""

import argparse
import re
from pathlib import Path
from typing import Dict, List, Tuple, Optional
import csv

# Derive project root from script location
# Script is at: <PROJECT_ROOT>/NuclearResearch/src/result_process/result_extraction/
PROJECT_ROOT = Path(__file__).resolve().parents[4]

# ============================================================================
# CONFIGURATION
# ============================================================================

VISUALIZATION_ROOT = PROJECT_ROOT / 'NuclearResearch' / 'results' / 'Visualization'
OUTPUT_DIR = PROJECT_ROOT / 'NuclearResearch' / 'results_summary'

EXPERIMENTS = ['exp0', 'exp1', 'exp2', 'exp3', 'exp4']
HORIZONS = ['30s', '300s', '600s']

# Specialist (trained) deep learning models
EXPECTED_MODELS = [
    'ARIMA', 'Autoformer', 'Crossformer', 'DLinear', 'ETSformer', 'FEDformer',
    'FreTS', 'GRU', 'Informer', 'LSTM', 'MICN',
    'MovingAverage', 'Naive', 'Nonstationary', 'PatchTST', 'Pyraformer',
    'Reformer', 'SCINet', 'SegRNN', 'TFT', 'TSMixer',
    'TimeMixer', 'TimesNet', 'Transformer', 'iTransformer'
]

# Foundation models (zero-shot, no training)
FOUNDATION_MODELS = ['Chronos', 'Chronos2', 'TimesFM']

# Fine-tuned foundation models
FINETUNED_MODELS = ['Chronos2_FT', 'Chronos_FT']

# ============================================================================
# EXTRACTION FUNCTIONS
# ============================================================================

def extract_average_metrics(summary_file: Path) -> Optional[Tuple[float, float]]:
    """
    Extract Average MAE and RMSE from metrics summary file.
    
    Args:
        summary_file: Path to *_ahead_metrics_summary.txt
    
    Returns:
        (mae, rmse) tuple, or None if file not found or parse error
    """
    if not summary_file.exists():
        return None
    
    try:
        with open(summary_file, 'r') as f:
            content = f.read()
        
        # Extract Average MAE
        mae_match = re.search(r'Average MAE:\s+([\d.]+)', content)
        # Extract Average RMSE
        rmse_match = re.search(r'Average RMSE:\s+([\d.]+)', content)
        
        if mae_match and rmse_match:
            mae = float(mae_match.group(1))
            rmse = float(rmse_match.group(1))
            return (mae, rmse)
        
        return None
        
    except Exception as e:
        print(f"ERROR parsing {summary_file}: {e}")
        return None


def get_metrics_file_path(exp: str, model: str, horizon: str) -> Path:
    """
    Get path to metrics summary file in centralized visualization location.

    Structure: {VISUALIZATION_ROOT}/{exp}/{horizon}_ahead/{model}_{horizon}_ahead_metrics_summary.txt

    Args:
        exp: Experiment ID (exp0-exp4)
        model: Model name (e.g., 'Transformer')
        horizon: Horizon name (30s, 300s, 600s)

    Returns:
        Path to metrics summary file
    """
    horizon_folder = f"{horizon}_ahead"
    filename = f"{model}_{horizon}_ahead_metrics_summary.txt"
    return VISUALIZATION_ROOT / exp / horizon_folder / filename


# ============================================================================
# MAIN EXTRACTION LOGIC
# ============================================================================

def extract_all_metrics(verbose: bool = True) -> List[Dict]:
    """
    Extract metrics from all experiments, models, and horizons.

    Searches centralized visualization location for all model/horizon combinations.

    Returns:
        List of dictionaries with keys: experiment, model, horizon, mae, rmse
    """
    all_metrics = []
    all_models = EXPECTED_MODELS + FOUNDATION_MODELS + FINETUNED_MODELS

    for exp in EXPERIMENTS:
        if verbose:
            print(f"\nProcessing {exp.upper()}...")

        exp_metrics_found = 0

        for model in all_models:
            for horizon in HORIZONS:
                # Get path to metrics file in centralized location
                summary_file = get_metrics_file_path(exp, model, horizon)

                # Extract metrics
                metrics = extract_average_metrics(summary_file)

                if metrics is None:
                    if verbose:
                        print(f"  SKIP: {model:20s} {horizon:5s} - No metrics file")
                    continue

                mae, rmse = metrics

                all_metrics.append({
                    'experiment': exp,
                    'model': model,
                    'horizon': horizon,
                    'mae': mae,
                    'rmse': rmse
                })

                exp_metrics_found += 1

                if verbose:
                    print(f"  OK:   {model:20s} {horizon:5s} - MAE={mae:.2f}, RMSE={rmse:.2f}")

        if verbose:
            print(f"  Total: {exp_metrics_found} metrics found for {exp}")

    return all_metrics


def apply_zero_shot_reference(metrics: List[Dict], reference_exp: str) -> int:
    """Use the zero-shot model metrics of `reference_exp` for all experiments."""
    reference = {
        (m['model'], m['horizon']): m for m in metrics
        if m['experiment'] == reference_exp and m['model'] in FOUNDATION_MODELS
    }
    replaced = 0
    for m in metrics:
        if m['model'] in FOUNDATION_MODELS and m['experiment'] != reference_exp:
            ref = reference.get((m['model'], m['horizon']))
            if ref is not None:
                m['mae'], m['rmse'] = ref['mae'], ref['rmse']
                replaced += 1
    return replaced


def save_metrics_csv(metrics: List[Dict], output_file: Path):
    """
    Save metrics to CSV file.
    
    Args:
        metrics: List of metric dictionaries
        output_file: Path to output CSV file
    """
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=['experiment', 'model', 'horizon', 'mae', 'rmse'])
        writer.writeheader()
        writer.writerows(metrics)
    
    print(f"\n{'='*80}")
    print(f"Saved {len(metrics)} metrics to: {output_file}")
    print(f"{'='*80}")


# ============================================================================
# MAIN
# ============================================================================

def main():
    parser = argparse.ArgumentParser(
        description='Extract MAE/RMSE metrics from visualization summary files'
    )
    
    parser.add_argument(
        '--output',
        type=str,
        default=None,
        help='Output CSV file path (default: results_summary/all_experiments_metrics.csv)'
    )
    
    parser.add_argument(
        '--quiet',
        action='store_true',
        help='Minimal output'
    )

    parser.add_argument(
        '--zero-shot-reference',
        type=str,
        default='exp4',
        choices=EXPERIMENTS + ['none'],
        help="Experiment whose zero-shot model results are used for all experiments ('none' to disable)"
    )

    args = parser.parse_args()
    
    # Determine output file
    if args.output:
        output_file = Path(args.output)
    else:
        output_file = OUTPUT_DIR / 'all_experiments_metrics.csv'
    
    verbose = not args.quiet
    
    # Extract metrics
    print("="*80)
    print("EXTRACTING METRICS FROM VISUALIZATION SUMMARIES")
    print("="*80)
    
    metrics = extract_all_metrics(verbose=verbose)

    if args.zero_shot_reference != 'none':
        n = apply_zero_shot_reference(metrics, args.zero_shot_reference)
        print(f"\nZero-shot models: {args.zero_shot_reference} results used for all experiments ({n} rows)")

    # Save to CSV
    save_metrics_csv(metrics, output_file)
    
    # Summary statistics
    if verbose:
        print(f"\nSummary:")
        print(f"  Total metrics extracted: {len(metrics)}")
        print(f"  Experiments: {len(set(m['experiment'] for m in metrics))}")
        print(f"  Unique models: {len(set(m['model'] for m in metrics))}")
        print(f"  Horizons: {', '.join(sorted(set(m['horizon'] for m in metrics)))}")


if __name__ == '__main__':
    main()
